function buildTrend(currentRent: number, annualGrowthRate: number): HistoricalTrendPoint[] {
  const startRent = currentRent / (1 + annualGrowthRate);
  const seasonalFactors = [
    0.0, 0.01, 0.025, 0.04, 0.055, 0.07, 0.085, 0.095, 0.1, 0.09, 0.095, 1.0,
  ];
  return MONTHS.map((month, idx) => {
    if (idx === MONTHS.length - 1) {
      return { month, avgRent: currentRent };
    }
    const progress = idx / (MONTHS.length - 1);
    const wave = Math.sin(idx * 0.7) * 0.008;
    const factor = progress + (seasonalFactors[idx] * 0.08 - 0.02) + wave;
    const interpolated = startRent + (currentRent - startRent) * Math.max(0, Math.min(1, factor));
    return {
      month,
      avgRent: Math.round(interpolated / 100) * 100,
    };
  });
}

